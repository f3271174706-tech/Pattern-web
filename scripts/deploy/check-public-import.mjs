import { chromium } from '@playwright/test';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const input = process.argv[2];
assert(input, 'Pass the supplied pattern.json path');
const raw = await readFile(input, 'utf8'), source = JSON.parse(raw);
const expected = JSON.parse(await readFile(new URL('../../examples/palettes/mard221.json', import.meta.url), 'utf8'));
const origin = 'https://perler.cloud';
const browser = await chromium.launch({ channel: process.platform === 'win32' ? 'msedge' : undefined, headless: true });
const context = await browser.newContext({ viewport: { width: 1600, height: 1040 } }), page = await context.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
let id;
try {
  assert.equal((await page.goto(origin + '/?import-check=' + Date.now(), { waitUntil: 'domcontentloaded', timeout: 45000 })).status(), 200);
  const config = await (await page.request.get(origin + '/api/v1/config')).json();
  assert.equal(config.authRequired, false); assert.equal(config.mode, 'public');
  await page.getByRole('button', { name: '导入新图纸' }).waitFor({ timeout: 20000 });
  assert.equal(await page.getByLabel('访问密钥', { exact: true }).count(), 0);
  const before = await (await page.request.get(origin + '/api/v1/patterns')).json();
  await page.getByRole('button', { name: '导入新图纸' }).click();
  await page.getByLabel('JSON 图纸文件').setInputFiles(input);
  const conflicts = Object.entries(source.palette).filter(([code, v]) => v.hex.toUpperCase() !== expected.colors[code].hex.toUpperCase()).length;
  await page.getByText(`${conflicts} 个色号的 HEX 与指定 MARD 色卡不同`).waitFor();
  assert.equal(await page.getByLabel('导入色值', { exact: true }).inputValue(), 'mard221');
  await page.getByText(`${conflicts} 个色号的 HEX 与指定 MARD 色卡不同`).click();
  await mkdir('output/deploy', { recursive: true });
  await page.screenshot({ path: 'output/deploy/legacy-import-preview.png' });
  const response = page.waitForResponse(r => r.url().endsWith('/api/v1/patterns') && r.request().method() === 'POST');
  await page.getByRole('dialog').getByRole('button', { name: '导入图纸', exact: true }).click();
  const createdResponse = await response; assert.equal(createdResponse.status(), 201);
  const state = await createdResponse.json(); id = state.pattern.patternId;
  await page.getByRole('heading', { name: source.name, exact: true }).waitFor();
  assert.deepEqual(state.pattern.grid.cells, source.grid);
  assert.deepEqual(state.pattern.palette, expected);
  const stats = await (await page.request.get(origin + '/api/v1/patterns/' + id + '/stats')).json();
  assert.equal(stats.beadCount, source.total_beads); assert.equal(stats.colorCount, source.color_count);
  const archived = await (await page.request.get(origin + `/api/v1/patterns/${id}/archives/${state.archives[0].id}`)).text();
  assert.equal(archived, raw);
  await page.reload(); await page.getByRole('heading', { name: source.name, exact: true }).waitFor();
  await page.getByRole('button', { name: '适应画布', exact: true }).click();
  await page.screenshot({ path: 'output/deploy/legacy-pattern-live.png' });
  assert.deepEqual(errors, []);
  assert.equal((await page.request.delete(origin + '/api/v1/patterns/' + id)).status(), 200); id = undefined;
  const after = await (await page.request.get(origin + '/api/v1/patterns')).json();
  assert.deepEqual(after.map(p => p.id).sort(), before.map(p => p.id).sort());
  const report = { origin, verifiedAt: new Date().toISOString(), authRequired: false, title: source.name, width: source.width, height: source.height, beads: stats.beadCount, colors: stats.colorCount, paletteConflicts: conflicts, originalSha256: createHash('sha256').update(raw).digest('hex'), checks: ['fresh browser opens without key or cookie', 'actual user file uploaded through GUI', 'HEX differences shown before import', 'all grid cells unchanged', 'exact supplied MARD palette', 'original JSON archived verbatim', 'refresh persists imported pattern', 'temporary probe removed and existing projects retained', 'no browser errors'] };
  await writeFile('output/deploy/public-import-verification.json', JSON.stringify(report, null, 2)); console.log(JSON.stringify(report));
} finally {
  if (id) await page.request.delete(origin + '/api/v1/patterns/' + id).catch(() => {});
  await browser.close();
}
